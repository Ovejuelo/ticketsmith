import type { TicketAnalysis } from '../../core/agent/index.ts'

const list = (items: readonly string[], empty: string, numbered = false): string =>
  items.length > 0
    ? items.map((item, index) => `${numbered ? `${index + 1}.` : '-'} ${item}`).join('\n')
    : `_${empty}_`

/** analysis.md: what the agent concluded and on what evidence, for a human to review. */
export const renderAnalysis = (
  key: string,
  analysis: TicketAnalysis,
  meta: { readonly playbook: string; readonly generatedAt: string },
): string =>
  [
    `# ${key}: analysis`,
    '',
    `> Generated by ticketsmith on ${meta.generatedAt} with the \`${meta.playbook}\` playbook. Review it before acting on it.`,
    '',
    `**Type:** ${analysis.ticketType} · **Confidence:** ${analysis.confidence}`,
    ...(analysis.suggestedTransition === undefined
      ? []
      : ['', `**Suggested transition:** ${analysis.suggestedTransition}`]),
    '',
    '## Summary',
    '',
    analysis.summary,
    '',
    '## Probable cause',
    '',
    analysis.probableCause,
    '',
    '## Evidence',
    '',
    list(
      analysis.evidence.map((e) => `**${e.source}** \`${e.reference}\`: ${e.finding}`),
      'No evidence was collected.',
    ),
    '',
    '## Next steps',
    '',
    list(analysis.nextSteps, 'None.', true),
    '',
    '## Open questions',
    '',
    list(analysis.openQuestions, 'None.'),
    '',
  ].join('\n')
