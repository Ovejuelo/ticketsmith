export type Confirm = {
  show(text: string): void
  ask(question: string): Promise<boolean>
}

// Ticketsmith's own header line in report.sql; the rest of the file is the query.
const GENERATED_HEADER = /^-- [A-Z][A-Z0-9_]*-\d+: report query, generated by ticketsmith\..*\n/
const PLACEHOLDER = /\[(EMAIL|PHONE|RFC|CURP|CLABE|CARD|SECRET)_\d+\]/

/** The report query of a ticket (out/<KEY>/report.sql, or a given file), without the header. */
export const readReport = async (
  outDir: string,
  key: string,
  file: string | undefined,
): Promise<Result<string, string>> => {
  const path = file ?? join(ticketOutputDir(outDir, key), REPORT_FILE)
  let text: string
  try {
    text = await readFile(path, 'utf8')
  } catch {
    return err(
      `No report query: ${path} does not exist (run \`ticketsmith process ${key}\` on a report ticket, or pass --file).`,
    )
  }
  const sql = text.replace(GENERATED_HEADER, '').trim()
  if (sql === '') return err(`${path} is empty.`)
  if (PLACEHOLDER.test(sql)) {
    return err(
      `${path} still has masked placeholders such as [EMAIL_1]: replace them with Metabase variables before publishing.`,
    )
  }
  return ok(sql)
}

/** Which Metabase database the question runs on: --db, or the only mapped one. */
export const pickDatabase = (
  config: MetabaseConfig,
  database: string | undefined,
): Result<{ readonly name: string; readonly id: number }, string> => {
  const mapped = Object.entries(config.databaseIds)
  if (mapped.length === 0) {
    return err('No project database is mapped to Metabase: run `ticketsmith project add metabase`.')
  }
  if (database === undefined) {
    const [only] = mapped
    if (mapped.length > 1 || only === undefined) {
      return err(`Pick the database with --db: ${mapped.map(([name]) => name).join(', ')}.`)
    }
    return ok({ name: only[0], id: only[1] })
  }
  const id = config.databaseIds[database]
  return id === undefined
    ? err(
        `"${database}" is not mapped to Metabase; mapped: ${mapped.map(([name]) => name).join(', ')}.`,
      )
    : ok({ name: database, id })
}

const preview = (card: NativeCard, config: MetabaseConfig, database: string): string =>
  [
    `Question to create in ${config.url}:`,
    '',
    `  Name:        ${card.name}`,
    `  Database:    ${database} (Metabase id ${card.databaseId})`,
    `  Collection:  ${card.collectionId ?? 'root'}`,
    `  Variables:   ${
      Object.values(card.templateTags)
        .map((tag) => `${tag.name} (${tag.type}${tag.required ? '' : ', optional'})`)
        .join(', ') || 'none'
    }`,
    '',
    card.sql,
    '',
  ].join('\n')

/**
 * Creates the report as a native Metabase question after the person read it and agreed.
 * Audited by hash, never by content; the link is kept in out/<KEY>/report.published.json.
 */
export const publishReport = async (
  client: MetabaseClient,
  config: MetabaseConfig,
  audit: AuditLog,
  outDir: string,
  input: {
    readonly key: TicketKey
    readonly sql: string
    readonly database: { readonly name: string; readonly id: number }
    readonly name: string
  },
  confirm: Confirm,
): Promise<Result<string | null, string>> => {
  const card: NativeCard = {
    name: input.name,
    description: `Report for ${input.key}, created with ticketsmith.`,
    databaseId: input.database.id,
    collectionId: config.collectionId ?? null,
    sql: input.sql,
    templateTags: templateTags(input.sql),
  }
  confirm.show(preview(card, config, input.database.name))
  if (!(await confirm.ask('Create this question in Metabase?'))) return ok(null)
  const started = Date.now()
  const created = await client.createCard(card)
  await audit.record({
    tool: 'metabase_publish',
    input: {
      ticket: input.key,
      database: input.database.name,
      sha256: createHash('sha256').update(input.sql).digest('hex'),
    },
    ok: created.ok,
    ...(created.ok ? {} : { error: describeMetabaseError(created.error) }),
    durationMs: Date.now() - started,
  })
  if (!created.ok) return err(describeMetabaseError(created.error))
  const written = await writeOutputFiles(ticketOutputDir(outDir, input.key), {
    'report.published.json': `${JSON.stringify({ id: created.value.id, url: created.value.url, at: new Date().toISOString() }, null, 2)}\n`,
  })
  return written.ok ? ok(created.value.url) : err(describeOutputError(written.error))
}
