import type { Investigation } from '../../core/agent/index.ts'

type Finding = Investigation['findings'][number]

const SEVERITY_ORDER: readonly Finding['severity'][] = ['high', 'medium', 'low', 'info']

/** Findings with the most severe first, keeping the agent's order within a severity. */
export const bySeverity = (findings: readonly Finding[]): readonly Finding[] =>
  [...findings].sort(
    (a, b) => SEVERITY_ORDER.indexOf(a.severity) - SEVERITY_ORDER.indexOf(b.severity),
  )

/** "1 high · 2 medium", or null when there are no findings. */
export const severityCounts = (findings: readonly Finding[]): string | null => {
  const counts = SEVERITY_ORDER.map(
    (severity) => [severity, findings.filter((f) => f.severity === severity).length] as const,
  ).filter(([, count]) => count > 0)
  return counts.length === 0 ? null : counts.map(([severity, n]) => `${n} ${severity}`).join(' · ')
}

const list = (items: readonly string[], empty: string, numbered = false): string =>
  items.length > 0
    ? items.map((item, index) => `${numbered ? `${index + 1}.` : '-'} ${item}`).join('\n')
    : `_${empty}_`

const quote = (text: string): string =>
  text
    .trim()
    .split('\n')
    .map((line) => `> ${line}`)
    .join('\n')

/** analysis.md of an investigation: the question, then the findings and their evidence. */
export const renderInvestigation = (
  question: string,
  investigation: Investigation,
  meta: { readonly playbook: string; readonly generatedAt: string },
): string =>
  [
    '# Investigation',
    '',
    quote(question),
    '',
    `_Generated by ticketsmith on ${meta.generatedAt} with the \`${meta.playbook}\` playbook. Review it before acting on it._`,
    '',
    '## Summary',
    '',
    investigation.summary,
    '',
    '## Findings',
    '',
    ...(investigation.findings.length === 0
      ? ['_No findings._', '']
      : bySeverity(investigation.findings).flatMap((finding, index) => [
          `### ${index + 1}. ${finding.title}`,
          '',
          `**Severity:** ${finding.severity} · **Confidence:** ${finding.confidence}`,
          '',
          list(
            finding.evidence.map((e) => `**${e.source}** \`${e.reference}\`: ${e.finding}`),
            'No evidence was collected.',
          ),
          '',
          `**Suggestion:** ${finding.suggestion}`,
          '',
        ])),
    '## Next steps',
    '',
    list(investigation.nextSteps, 'None.', true),
    '',
    '## Open questions',
    '',
    list(investigation.openQuestions, 'None.'),
    '',
  ].join('\n')
