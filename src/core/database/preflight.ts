import { err, ok, type Result } from '../kernel/index.ts'
import type { DatabaseAdapter } from './database-adapter.port.ts'
import { describeDatabaseError } from './describe-error.ts'
import { guardReadQuery } from './readonly-guard.ts'
import { quoteIdentifier, sqlLiteral } from './sql-literal.ts'
import type { GuardedChange } from './write-guard.ts'

export const SAMPLE_ROWS = 10

export type Preflight = {
  /** Rows the change will affect. */
  readonly rows: number
  /** The current values of the affected rows (primary key + changed columns), first rows only. */
  readonly sample: readonly Readonly<Record<string, unknown>>[]
  /** Whether finding the rows uses an index (UPDATE only). */
  readonly usesIndex: boolean | null
  /** UPDATE: restores the captured values. INSERT: written after execution, from the new keys. */
  readonly rollbackSql: string | null
}

/**
 * Measures a guarded change without writing: an UPDATE's WHERE becomes a guarded SELECT of the
 * primary key and the changed columns, which counts the rows, captures their current values for
 * the rollback script and is EXPLAINed. Rejects changes that match nothing or more than maxRows.
 */
export const preflightChange = async (
  adapter: DatabaseAdapter,
  change: GuardedChange,
  options: { readonly maxRows: number; readonly changeId: string },
): Promise<Result<Preflight, string>> => {
  if (change.kind === 'insert') {
    const rows = change.insertRows ?? 0
    if (rows > options.maxRows) {
      return err(
        `The INSERT adds ${rows} rows; the project allows at most ${options.maxRows} per change.`,
      )
    }
    return ok({ rows, sample: [], usesIndex: null, rollbackSql: null })
  }

  const q = (name: string) => quoteIdentifier(name, change.dialect)
  const columns = [...new Set([...change.primaryKey, ...change.columns])]
  const select = `SELECT ${columns.map(q).join(', ')} FROM ${q(change.table)} WHERE ${change.whereSql}`
  if (adapter.dialect !== change.dialect) {
    return err(
      `The change was written for ${change.dialect}, but the database is ${adapter.dialect}.`,
    )
  }
  const query = guardReadQuery(select, { dialect: change.dialect, maxRows: options.maxRows })
  if (!query.ok) return err(`The preflight query was rejected: ${query.error.reason}`)
  const result = await adapter.runReadQuery(query.value)
  if (!result.ok) return err(describeDatabaseError(result.error))
  if (result.value.truncated) {
    return err(
      `The UPDATE matches more than ${options.maxRows} rows (the project's changes.maxRows); narrow the WHERE.`,
    )
  }
  if (result.value.rows.length === 0)
    return err('The UPDATE matches no rows; check the WHERE with db_select.')
  const explained = await adapter.explain(query.value)

  return ok({
    rows: result.value.rows.length,
    sample: result.value.rows.slice(0, SAMPLE_ROWS),
    usesIndex: explained.ok ? explained.value.usesIndex : null,
    rollbackSql: updateRollback(change, result.value.rows, options.changeId),
  })
}

const HEADER = (changeId: string) => [
  `-- Rollback for change ${changeId}, generated by ticketsmith before it ran.`,
  '-- REVIEW BEFORE RUNNING. Ticketsmith never runs this script; run it yourself if needed.',
  'START TRANSACTION;',
]
const FOOTER = ['-- Check the result, then:', '-- COMMIT;', 'ROLLBACK;', '']

const keyCondition = (change: GuardedChange, row: Readonly<Record<string, unknown>>): string =>
  change.primaryKey
    .map(
      (key) => `${quoteIdentifier(key, change.dialect)} = ${sqlLiteral(row[key], change.dialect)}`,
    )
    .join(' AND ')

/** One UPDATE per row putting back the values captured before the change. */
export const updateRollback = (
  change: GuardedChange,
  rows: readonly Readonly<Record<string, unknown>>[],
  changeId: string,
): string =>
  [
    ...HEADER(changeId),
    ...rows.map(
      (row) =>
        `UPDATE ${quoteIdentifier(change.table, change.dialect)} SET ${change.columns
          .map(
            (column) =>
              `${quoteIdentifier(column, change.dialect)} = ${sqlLiteral(row[column], change.dialect)}`,
          )
          .join(', ')} WHERE ${keyCondition(change, row)};`,
    ),
    ...FOOTER,
  ].join('\n')

/**
 * Removes the rows an INSERT added, from the keys it listed or the AUTO_INCREMENT ids it got.
 * A script for a human only: Ticketsmith never runs it (and never runs DELETE).
 */
export const insertRollback = (
  change: GuardedChange,
  insertedKeys: readonly Readonly<Record<string, unknown>>[] | null,
  changeId: string,
): string =>
  insertedKeys === null
    ? [
        `-- Rollback for change ${changeId}: the inserted rows' keys are unknown (no AUTO_INCREMENT id and`,
        `-- the INSERT did not list the primary key). Find them in ${change.table} and remove them by hand.`,
        '',
      ].join('\n')
    : [
        ...HEADER(changeId),
        ...insertedKeys.map(
          (key) =>
            `DELETE FROM ${quoteIdentifier(change.table, change.dialect)} WHERE ${keyCondition(change, key)};`,
        ),
        ...FOOTER,
      ].join('\n')
