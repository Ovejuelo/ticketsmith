export type BriefSection = {
  readonly title: string
  /** Path relative to the knowledge folder, e.g. tickets/jira.md */
  readonly file: string
  readonly summary: string
}

export type BriefInput = {
  readonly project: string
  readonly integrations: readonly string[]
  readonly sections: readonly BriefSection[]
  readonly generatedAt: string
}

/** The entry point the agent reads before any task: what the project has and where to look. */
export const renderBrief = ({ project, integrations, sections, generatedAt }: BriefInput): string =>
  [
    `# Project brief: ${project}`,
    '',
    `Generated by Ticketsmith on ${generatedAt}. Regenerate with \`ticketsmith project refresh\`.`,
    '',
    '## Integrations',
    '',
    integrations.length > 0
      ? integrations.map((integration) => `- ${integration}`).join('\n')
      : '- None yet. Add one with `ticketsmith project add <integration>`.',
    '',
    '## Knowledge',
    '',
    sections.length > 0
      ? sections.map((s) => `- **[${s.title}](${s.file})**: ${s.summary}`).join('\n')
      : '- Nothing investigated yet.',
    '',
    '## How to use this brief',
    '',
    '- Read the linked files before working on a task in this project.',
    '- Sensitive values appear as placeholders such as `[EMAIL_1]`; never try to recover them.',
    '- Everything in this folder is shared with the team through the project repository.',
    '',
  ].join('\n')
