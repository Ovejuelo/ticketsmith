import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import type { MetabaseConfig } from '#src/core/project/index.ts'
import { TicketKeySchema } from '#src/core/tickets/index.ts'
import { pickDatabase, publishReport, readReport } from '#src/features/metabase/publish-report.ts'
import { FakeCli, testDatabase, testProject, withDatabases } from '#tests/support/fake-cli.ts'
import { FakeMetabase } from '#tests/support/fake-metabase.ts'
import { InMemoryAuditLog } from '#tests/support/in-memory-audit-log.ts'

const KEY = TicketKeySchema.parse('OPS-7')
const config: MetabaseConfig = {
  type: 'metabase',
  url: 'https://metabase.example.com',
  databaseIds: { shard1: 3, ledger: 4 },
  collectionId: 9,
}
const SQL =
  'SELECT * FROM invoices\nWHERE created_at >= {{start_date}}\n[[AND account_id = {{account_id}}]]'

describe('publishing a report to Metabase', () => {
  let out: string
  const shown: string[] = []
  const answering = (yes: boolean) => ({ show: (t: string) => shown.push(t), ask: async () => yes })
  beforeEach(async () => {
    out = await mkdtemp(join(tmpdir(), 'ticketsmith-mb-'))
    await mkdir(join(out, 'OPS-7'))
    await writeFile(
      join(out, 'OPS-7', 'report.sql'),
      `-- OPS-7: report query, generated by ticketsmith. REVIEW BEFORE USING.\n${SQL}\n`,
    )
    shown.length = 0
  })
  afterEach(() => rm(out, { recursive: true, force: true }))

  it('reads report.sql without its header and refuses masked placeholders', async () => {
    expect(await readReport(out, 'OPS-7', undefined)).toEqual({ ok: true, value: SQL })
    await writeFile(join(out, 'OPS-7', 'bad.sql'), "SELECT 1 WHERE email = '[EMAIL_1]@x.mx'")
    expect(await readReport(out, 'OPS-7', join(out, 'OPS-7', 'bad.sql'))).toMatchObject({
      ok: false,
      error: expect.stringContaining('placeholders'),
    })
    expect((await readReport(out, 'OPS-8', undefined)).ok).toBe(false)
  })

  it('picks the database: --db, or the only mapped one', () => {
    expect(pickDatabase(config, 'ledger')).toEqual({ ok: true, value: { name: 'ledger', id: 4 } })
    expect(pickDatabase(config, undefined)).toMatchObject({
      ok: false,
      error: expect.stringContaining('--db: shard1, ledger'),
    })
    expect(pickDatabase({ ...config, databaseIds: { shard1: 3 } }, undefined)).toEqual({
      ok: true,
      value: { name: 'shard1', id: 3 },
    })
    expect(pickDatabase(config, 'nope').ok).toBe(false)
  })

  it('shows the question, creates it only on yes, audits by hash and keeps the link', async () => {
    const metabase = new FakeMetabase()
    const audit = new InMemoryAuditLog()
    const input = {
      key: KEY,
      sql: SQL,
      database: { name: 'shard1', id: 3 },
      name: 'OPS-7: invoices',
    }

    expect(await publishReport(metabase, config, audit, out, input, answering(false))).toEqual({
      ok: true,
      value: null,
    })
    expect(metabase.cards).toEqual([])
    expect(shown[0]).toContain('Variables:   start_date (date), account_id (number, optional)')

    expect(await publishReport(metabase, config, audit, out, input, answering(true))).toEqual({
      ok: true,
      value: 'https://metabase.example.com/question/101',
    })
    expect(metabase.cards[0]).toMatchObject({ databaseId: 3, collectionId: 9, sql: SQL })
    expect(audit.entries[0]).toMatchObject({
      tool: 'metabase_publish',
      ok: true,
      input: { ticket: 'OPS-7', database: 'shard1' },
    })
    expect(JSON.stringify(audit.entries)).not.toContain('invoices')
    expect(
      JSON.parse(await readFile(join(out, 'OPS-7', 'report.published.json'), 'utf8')).url,
    ).toBe('https://metabase.example.com/question/101')
  })
})

describe('ticketsmith project add metabase and metabase publish', () => {
  let cli: FakeCli
  beforeEach(async () => {
    cli = await (await FakeCli.create()).withProject(
      withDatabases(testProject(null), [testDatabase('shard1')]),
    )
  })
  afterEach(() => cli.cleanup())

  it('adds Metabase from flags, checking the key and the mapping, then investigates it', async () => {
    const add = (...flags: string[]) => cli.run('project', 'add', 'metabase', ...flags)
    expect((await add('--url', 'https://metabase.example.com'))?.message).toMatch(
      /TICKETSMITH_METABASE_API_KEY/,
    )
    await cli.secrets.set({ project: 'acme', name: 'metabase-api-key' }, 'mb_key')
    expect(
      (await add('--url', 'https://metabase.example.com', '--map', 'shard1=99'))?.message,
    ).toMatch(/no database with id 99/)
    expect(
      (await add('--url', 'https://metabase.example.com', '--map', 'other=3'))?.message,
    ).toMatch(/Not databases of this project: other/)
    expect(
      await add('--url', 'https://metabase.example.com/', '--map', 'shard1=3', '--collection', '9'),
    ).toBeNull()
    const project = await cli.services.projects.load('acme')
    expect(project.ok && project.value.integrations.metabase).toEqual({
      type: 'metabase',
      url: 'https://metabase.example.com',
      databaseIds: { shard1: 3 },
      collectionId: 9,
    })
    expect(cli.metabase.connections.at(-1)).toEqual({
      url: 'https://metabase.example.com',
      apiKey: 'mb_key',
    })
    expect(cli.stdout + cli.stderr).toContain(
      'Metabase with 2 database(s); 1 mapped to project databases.',
    )

    expect((await cli.run('metabase', 'publish', 'OPS-7'))?.message).toMatch(/interactive terminal/)
  })
})
