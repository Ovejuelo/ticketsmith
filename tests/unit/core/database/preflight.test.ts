import { describe, expect, it } from 'vitest'
import type { TableInfo } from '#src/core/database/index.ts'
import {
  guardChange,
  insertRollback,
  preflightChange,
  sqlLiteral,
} from '#src/core/database/index.ts'
import { ok } from '#src/core/kernel/index.ts'
import { emptyResult, FakeDatabaseAdapter } from '#tests/support/fake-database.ts'

const accounts: TableInfo = {
  name: 'accounts',
  comment: '',
  estimatedRows: 10,
  columns: ['id', 'email', 'status', 'note', 'updated_at'].map((name) => ({
    name,
    type: 'varchar(255)',
    nullable: true,
    key: name === 'id' ? 'PRI' : '',
    default: null,
    comment: '',
  })),
  foreignKeys: [],
  indexes: [],
}

const change = (sql: string) => {
  const guarded = guardChange(sql, { dialect: 'mysql', tables: [accounts] })
  if (!guarded.ok) throw new Error(guarded.error.reason)
  return guarded.value
}

describe('sqlLiteral', () => {
  it('renders values as MySQL literals', () => {
    expect(sqlLiteral(null)).toBe('NULL')
    expect(sqlLiteral(42)).toBe('42')
    expect(sqlLiteral('12345678901234567890')).toBe("'12345678901234567890'")
    expect(sqlLiteral("O'Brien \\ \n")).toBe("'O\\'Brien \\\\ \\n'")
    expect(sqlLiteral('2026-10-16 10:00:00')).toBe("'2026-10-16 10:00:00'")
    expect(sqlLiteral(Buffer.from([0xde, 0xad]))).toBe("X'dead'")
  })

  it('renders standard-conforming PostgreSQL literals', () => {
    expect(sqlLiteral("O'Brien \\ \n", 'postgres')).toBe("'O''Brien \\ \n'")
    expect(sqlLiteral(true, 'postgres')).toBe('TRUE')
    expect(sqlLiteral(Buffer.from([0xde, 0xad]), 'postgres')).toBe("'\\xdead'::bytea")
    expect(sqlLiteral({ a: 1 }, 'postgres')).toBe('\'{"a":1}\'')
  })
})

describe('preflightChange', () => {
  it('counts the rows, samples them, checks the index and writes the rollback', async () => {
    const db = new FakeDatabaseAdapter('shard1')
    db.answer = () =>
      ok({
        ...emptyResult,
        columns: ['id', 'status', 'note'],
        rows: [
          { id: 7, status: 'active', note: null },
          { id: 8, status: "it's ok", note: '2026-10-16 10:00:00' },
        ],
      })
    db.usesIndex = false

    const result = await preflightChange(
      db,
      change("UPDATE accounts SET status = 'inactive', note = 'closed' WHERE id IN (7, 8)"),
      { maxRows: 100, changeId: 'cr-1' },
    )

    expect(db.queries[0]).toBe(
      'SELECT `id`, `status`, `note` FROM `accounts` WHERE `id` IN (7, 8) LIMIT 101',
    )
    expect(db.queries[1]).toMatch(/^EXPLAIN SELECT/)
    expect(result).toEqual({
      ok: true,
      value: {
        rows: 2,
        sample: [
          { id: 7, status: 'active', note: null },
          { id: 8, status: "it's ok", note: '2026-10-16 10:00:00' },
        ],
        usesIndex: false,
        rollbackSql: [
          '-- Rollback for change cr-1, generated by ticketsmith before it ran.',
          '-- REVIEW BEFORE RUNNING. Ticketsmith never runs this script; run it yourself if needed.',
          'START TRANSACTION;',
          "UPDATE `accounts` SET `status` = 'active', `note` = NULL WHERE `id` = 7;",
          "UPDATE `accounts` SET `status` = 'it\\'s ok', `note` = '2026-10-16 10:00:00' WHERE `id` = 8;",
          '-- Check the result, then:',
          '-- COMMIT;',
          'ROLLBACK;',
          '',
        ].join('\n'),
      },
    })
  })

  it('quotes the PostgreSQL way and refuses a database of another engine', async () => {
    const db = new FakeDatabaseAdapter('pg1')
    db.dialect = 'postgres'
    db.answer = () => ok({ ...emptyResult, rows: [{ id: 7, status: "it's" }] })
    const guarded = guardChange("UPDATE accounts SET status = 'x' WHERE id = 7", {
      dialect: 'postgres',
      tables: [accounts],
    })
    if (!guarded.ok) throw new Error(guarded.error.reason)

    const result = await preflightChange(db, guarded.value, { maxRows: 100, changeId: 'cr-3' })
    expect(db.queries[0]).toBe('SELECT "id", "status" FROM "accounts" WHERE id = 7 LIMIT 101')
    expect(result.ok && result.value.rollbackSql).toContain(
      'UPDATE "accounts" SET "status" = \'it\'\'s\' WHERE "id" = 7;',
    )

    db.dialect = 'mysql'
    expect(await preflightChange(db, guarded.value, { maxRows: 100, changeId: 'cr-3' })).toEqual({
      ok: false,
      error: 'The change was written for postgres, but the database is mysql.',
    })
  })

  it('rejects UPDATEs that match nothing or more than the maximum', async () => {
    const db = new FakeDatabaseAdapter('shard1')
    const update = change("UPDATE accounts SET status = 'x' WHERE status = 'active'")

    expect(await preflightChange(db, update, { maxRows: 100, changeId: 'cr-1' })).toEqual({
      ok: false,
      error: 'The UPDATE matches no rows; check the WHERE with db_select.',
    })

    db.answer = () => ok({ ...emptyResult, rows: [{ id: 1 }, { id: 2 }], truncated: true })
    expect(await preflightChange(db, update, { maxRows: 2, changeId: 'cr-1' })).toMatchObject({
      ok: false,
      error: expect.stringContaining('more than 2 rows'),
    })
  })

  it('counts INSERT rows without touching the database; the rollback comes after it runs', async () => {
    const db = new FakeDatabaseAdapter('shard1')
    const insert = change(
      "INSERT INTO accounts (email, status) VALUES ('a@x.mx', 'new'), ('b@x.mx', 'new')",
    )
    expect(await preflightChange(db, insert, { maxRows: 100, changeId: 'cr-2' })).toEqual({
      ok: true,
      value: { rows: 2, sample: [], usesIndex: null, rollbackSql: null },
    })
    expect(db.queries).toEqual([])
    expect((await preflightChange(db, insert, { maxRows: 1, changeId: 'cr-2' })).ok).toBe(false)

    expect(insertRollback(insert, [{ id: 41 }, { id: 42 }], 'cr-2')).toContain(
      'DELETE FROM `accounts` WHERE `id` = 41;\nDELETE FROM `accounts` WHERE `id` = 42;',
    )
    expect(insertRollback(insert, null, 'cr-2')).toMatch(/keys are unknown/)
  })
})
